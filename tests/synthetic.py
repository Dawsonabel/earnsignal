"""SYNTHETIC TEST DATA — for automated tests only.

Builds a throwaway SQLite database with fake companies (tickers A1..B6) whose
data is generated by a known process, so tests can check that the pipeline
(a) never uses information from after an event's cutoff and (b) can recover a
signal that was deliberately planted. Nothing here is written to the real
database, and none of these values describe real companies.
"""
from __future__ import annotations

import math
from datetime import date, timedelta

import numpy as np
import pandas as pd

from earnsignal import db

SEGMENTS = {"alpha": [f"A{i}" for i in range(1, 7)], "beta": [f"B{i}" for i in range(1, 7)]}
START, END = date(2016, 1, 1), date(2024, 12, 31)


def quarter_ends(start: date, end: date) -> list[date]:
    out = []
    for y in range(start.year, end.year + 1):
        for m, d in ((3, 31), (6, 30), (9, 30), (12, 31)):
            q = date(y, m, d)
            if start <= q <= end:
                out.append(q)
    return out


def build(path, seed: int = 7, signal_beta: float = 0.08, today: date = date(2025, 1, 10)) -> dict:
    rng = np.random.default_rng(seed)
    con = db.connect(path)
    db.init(con)
    tickers = [t for g in SEGMENTS.values() for t in g]
    db.upsert(con, "companies", [
        {"ticker": t, "name": f"Synthetic {t}", "cik": 1000 + i, "segment": seg, "fiscal_year_end": 12,
         "ats_provider": None, "ats_token": None, "wikipedia": "[]", "ios_app_id": None, "notes": "SYNTHETIC", "updated_at": db.now_utc()}
        for i, (seg, t) in enumerate((s, t) for s, ts in SEGMENTS.items() for t in ts)
    ])
    days = pd.bdate_range(START, END)
    n = len(days)
    spy = 100 * np.exp(np.cumsum(rng.normal(0.0003, 0.01, n)))
    qends = quarter_ends(START, END)

    # latent demand: log level per quarter per ticker
    demand = {t: np.cumsum(rng.normal(0.02, 0.12, len(qends))) for t in tickers}
    jumps: dict[str, dict] = {t: {} for t in tickers}
    events, fund, cons, wiki_rows, ins_rows = [], [], [], [], []
    truth = []
    for t in tickers:
        L = demand[t]
        rev = 1e8 * np.exp(L + 0.03 * np.arange(len(qends)))
        eps = 0.5 + 0.8 * L + rng.normal(0, 0.05, len(qends))
        for qi, qe in enumerate(qends):
            ann = qe + timedelta(days=int(rng.integers(24, 40)))
            while ann.weekday() >= 5:
                ann += timedelta(days=1)
            if ann > END - timedelta(days=5):
                continue
            timing = "AMC" if rng.random() < 0.6 else "BMO"
            yoy = L[qi] - L[qi - 4] if qi >= 4 else 0.0
            events.append({"ticker": t, "announce_date": ann.isoformat(), "announce_ts": None, "timing": timing,
                           "period_end": qe.isoformat(), "source": "sec_8k_202", "accession": f"{t}-{qi}",
                           "url": f"https://example.invalid/{t}/{qi}", "status": "reported", "retrieved_at": db.now_utc()})
            # planted signal: announcement jump depends on the quarter's YoY demand change
            jumps[t][ann] = (timing, signal_beta * yoy + rng.normal(0, 0.05))
            truth.append({"ticker": t, "announce_date": ann.isoformat(), "true_yoy": yoy})
            filed_q = (ann + timedelta(days=10)).isoformat()
            qs = (qe - pd.DateOffset(months=3) + pd.Timedelta(days=1)).date()
            if qe.month != 12:  # 10-Q quarterly facts (Q4 only via the annual 10-K)
                for metric, tag, val in (("revenue", "Revenues", rev[qi]), ("eps_diluted", "EarningsPerShareDiluted", eps[qi])):
                    fund.append({"ticker": t, "metric": metric, "tag": tag, "period_start": qs.isoformat(),
                                 "period_end": qe.isoformat(), "duration_days": (qe - qs).days, "fiscal_year": qe.year,
                                 "fiscal_period": f"Q{(qe.month) // 3}", "form": "10-Q", "accession": f"{t}-{qi}-q",
                                 "filed_date": filed_q, "value": float(val), "derived": 0, "source_url": "synthetic", "retrieved_at": db.now_utc()})
                    # the same quarter re-reported a year later as a comparative, RESTATED (+20%)
                    fund.append({**fund[-1], "accession": f"{t}-{qi}-restated",
                                 "filed_date": (ann + timedelta(days=375)).isoformat(), "value": float(val) * 1.2})
            else:
                ys = date(qe.year, 1, 1)
                idx = [k for k, x in enumerate(qends) if x.year == qe.year]
                for metric, tag, arr in (("revenue", "Revenues", rev), ("eps_diluted", "EarningsPerShareDiluted", eps)):
                    fund.append({"ticker": t, "metric": metric, "tag": tag, "period_start": ys.isoformat(),
                                 "period_end": qe.isoformat(), "duration_days": (qe - ys).days, "fiscal_year": qe.year,
                                 "fiscal_period": "FY", "form": "10-K", "accession": f"{t}-{qi}-k",
                                 "filed_date": (ann + timedelta(days=20)).isoformat(), "value": float(sum(arr[k] for k in idx)),
                                 "derived": 0, "source_url": "synthetic", "retrieved_at": db.now_utc()})
            est = eps[qi] - (0.6 * yoy + rng.normal(0, 0.05))
            cons.append({"ticker": t, "announce_ts": None, "announce_date": ann.isoformat(), "eps_estimate": float(est),
                         "eps_reported": float(eps[qi]), "surprise_pct": float((eps[qi] - est) / abs(est) * 100) if est else None,
                         "source": "yahoo", "source_url": "synthetic", "retrieved_at": db.now_utc()})
        # wikipedia: daily views follow the latent demand level of the quarter
        for qi, qe in enumerate(qends):
            qs = (qe - pd.DateOffset(months=3) + pd.Timedelta(days=1)).date()
            d = qs
            while d <= qe:
                if d >= date(2015, 7, 1):
                    v = 5000 * math.exp(demand[t][qi]) * math.exp(rng.normal(0, 0.15))
                    wiki_rows.append({"source": "wikipedia", "ticker": t, "series": f"pageviews:{t}", "obs_date": d.isoformat(),
                                      "value": float(round(v)), "meta": None, "source_url": "synthetic", "observed_at": db.now_utc()})
                d += timedelta(days=1)
        # insiders: occasional open-market buys and sales
        for k in range(int(rng.integers(5, 15))):
            fd = START + timedelta(days=int(rng.integers(0, (END - START).days)))
            code = "P" if rng.random() < 0.3 else "S"
            ins_rows.append({"accession": f"{t}-ins-{k}", "seq": "1", "ticker": t, "issuer_cik": 0, "filing_date": fd.isoformat(),
                             "trans_date": fd.isoformat(), "owner_name": f"Insider {k % 4}", "owner_relationship": "Officer",
                             "owner_title": "VP", "trans_code": code, "acq_disp": "A" if code == "P" else "D",
                             "shares": 1000.0, "price": 50.0, "value": 50000.0, "security_title": "Common",
                             "source": "synthetic", "retrieved_at": db.now_utc()})

    # prices
    price_rows = []
    for t in tickers + ["SPY"]:
        if t == "SPY":
            series = spy
        else:
            r = 1.1 * np.diff(np.log(np.r_[spy[0], spy])) + rng.normal(0, 0.015, n)
            day_idx = {d.date(): i for i, d in enumerate(days)}
            for ann, (timing, j) in jumps[t].items():
                # reaction lands on the first close after the release
                i = day_idx.get(ann)
                if i is None:
                    continue
                k = i + 1 if timing == "AMC" else i
                if k < n:
                    r[k] += j
            series = 50 * np.exp(np.cumsum(r))
        for d, v in zip(days, series):
            price_rows.append({"ticker": t, "date": d.date().isoformat(), "open": v, "high": v, "low": v, "close": v,
                               "adj_close": v, "volume": 1e6, "source": "synthetic", "retrieved_at": db.now_utc()})

    # upcoming scheduled announcements relative to `today`
    upcoming = []
    for k, t in enumerate(tickers):
        a = today + timedelta(days=7 + k)
        upcoming.append({"ticker": t, "announce_date": a.isoformat(), "announce_ts": None, "timing": "AMC", "period_end": None,
                         "source": "yahoo", "accession": None, "url": "synthetic", "status": "scheduled", "retrieved_at": db.now_utc()})

    db.upsert(con, "earnings_events", events + upcoming)
    db.upsert(con, "fundamentals", fund)
    db.upsert(con, "consensus", cons)
    db.upsert(con, "observations", wiki_rows)
    db.upsert(con, "insider_transactions", ins_rows)
    db.upsert(con, "prices", price_rows)
    con.commit()
    con.close()
    return {"tickers": tickers, "truth": pd.DataFrame(truth), "today": today}
